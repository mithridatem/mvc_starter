-- Créer la base DATABASE_NAME avant d'exécuter ce script (psql -d <nom_base> -f database/postgresql.sql).
CREATE TABLE IF NOT EXISTS "user" (
    id_user INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(50) NOT NULL,
    lastname VARCHAR(50) NOT NULL,
    email VARCHAR(50) UNIQUE NOT NULL,
    hash_password VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NULL,
    img_profil VARCHAR(200) NULL,
    "grant" VARCHAR(50) NULL
);
